import { randomUUID } from "node:crypto";
import { access, chmod, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, posix, win32 } from "node:path";
import { createServiceLogger, type ServiceLogger } from "#src/logger/serviceLogger.js";
import { getAppConfigDir } from "#src/paths.js";
import { findZCodeAgentRuntimeNodeBundle } from "../../runtime-tools/providerRuntimeResolver.js";

/**
 * Rust 内核的 MCP 无 Node 回退（docs/design/v2/mcp-node-fallback.md）。
 *
 * Rust app-server 由 Host spawn，MCP 子进程的环境来自内核入口的环境快照（白名单投影），
 * 所以 PATH / 两个回退变量必须由 Host 注入 agent 进程本身：内核无需任何 MCP 特判，
 * 用户自己的 node/npm/npx 仍按 PATH 顺序优先，shim 目录只在最后兜底。
 *
 * shim 内容与 adapters/mcp/node-fallback.ts 保持逐字一致（布局 v1）：两边各自维护目录，
 * 只有语义需要同步；真实路径仍经环境变量传入，shim 文件本身是静态的。
 */
export const MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY = "NIBI_NODE_FALLBACK_EXEC_PATH";
export const MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY = "NIBI_NODE_FALLBACK_NPM_ROOT";
export const MCP_NODE_FALLBACK_SHIM_LAYOUT = "v1";
const NPM_CLI_ENTRY = "npm-cli.js";
const NPX_CLI_ENTRY = "npx-cli.js";
const SHIM_EXECUTABLE_MODE = 0o755;
const EXECUTABLE_BITS = 0o111;
const MISSING_ENV_EXIT_CODE = 127;
const PATH_ENV_KEY = "PATH";

export interface McpNodeFallbackHostEnvInput {
  /** 只给 Rust 内核注入：Node 内核由 bootstrap 的 MCP 适配器自己做回退。 */
  kernel: "node" | "rust";
  /** Host 的 Electron 可执行文件（utilityProcess 的 process.execPath）。 */
  execPath: string;
  logger?: ServiceLogger;
  /**
   * 是否运行在桌面 Electron utilityProcess 里。远程 Host（裸 Node）沿用原来的 PATH 规则，
   * 不写 shim；测试可直接注入。
   */
  isElectron?: boolean;
  /** 随包 npm 根目录候选，按顺序取第一个完整的；缺省用 agent bundle 旁的 node-runtime/npm。 */
  npmRootCandidates?: readonly string[];
  platform?: NodeJS.Platform;
  /** 测试注入；缺省基于当前进程 env 计算 PATH。 */
  processEnv?: Record<string, string | undefined>;
  /** shim 目录落在 `<storageRoot>/node-fallback/<layout>`；缺省为桌面 app 配置目录。 */
  storageRoot?: string;
}

/**
 * 生成 agent spawn env 的补丁。失败时返回空补丁：没有 fallback 时连接照常进行，
 * 用户看到的就是原本的 spawn ENOENT，而不是 agent 起不来。
 */
export async function buildMcpNodeFallbackHostEnv(
  input: McpNodeFallbackHostEnvInput,
): Promise<Record<string, string | undefined>> {
  if (input.kernel !== "rust" || !(input.isElectron ?? Boolean(process.versions.electron))) {
    return {};
  }
  const platform = input.platform ?? process.platform;
  const storageRoot = input.storageRoot ?? getAppConfigDir();
  const binDir = join(storageRoot, "node-fallback", MCP_NODE_FALLBACK_SHIM_LAYOUT);
  const logger = input.logger ?? createServiceLogger("mcp-node-fallback");

  try {
    await ensureMcpNodeFallbackShimDir(binDir, platform);
    const npmRootCandidates = input.npmRootCandidates ?? defaultNpmRootCandidates();
    const npmRoot = await resolveBundledNpmRoot(npmRootCandidates);
    const pathValue = selectPathValue(input.processEnv ?? process.env, platform);
    return {
      ...fallbackPathPatch(pathValue, binDir, platform),
      [MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY]: input.execPath,
      ...(npmRoot ? { [MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY]: npmRoot } : {}),
    };
  } catch (error) {
    logger.warn("MCP node fallback for the Rust kernel is unavailable", {
      binDir,
      error: error instanceof Error ? error.message : String(error),
      event: "mcp.node_fallback.host_unavailable",
      module: "services.mcp_node_fallback",
    });
    return {};
  }
}

/**
 * agent bundle 旁的随包 npm（与 bootstrap 的 `node-runtime/npm` 同一约定）。
 * 开发态 bundle 通常没有 staged npm：此时只提供 node shim，npm/npx shim 以 127 报缺变量。
 */
export function defaultNpmRootCandidates(): string[] {
  const bundlePath = findZCodeAgentRuntimeNodeBundle();
  return bundlePath ? [join(dirname(bundlePath), "node-runtime", "npm")] : [];
}

export function renderMcpNodeFallbackShims(
  platform: NodeJS.Platform,
): Array<{ content: string; executable: boolean; name: string }> {
  return [
    { command: "node" as const },
    { command: "npm" as const, npmEntry: NPM_CLI_ENTRY },
    { command: "npx" as const, npmEntry: NPX_CLI_ENTRY },
  ].map((target) =>
    platform === "win32"
      ? { content: renderWindowsShim(target), executable: false, name: `${target.command}.cmd` }
      : { content: renderPosixShim(target), executable: true, name: target.command },
  );
}

interface ShimTarget {
  npmEntry?: string;
  command: string;
}

function renderPosixShim(target: ShimTarget): string {
  const lines = [
    "#!/bin/sh",
    `# Generated by NIBI: ${target.command} fallback on the Electron Node runtime.`,
    ...renderPosixEnvGuard(MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY),
    ...(target.npmEntry ? renderPosixEnvGuard(MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY) : []),
    "ELECTRON_RUN_AS_NODE=1",
    "export ELECTRON_RUN_AS_NODE",
  ];
  if (target.npmEntry) {
    lines.push(
      ': "${npm_config_update_notifier:=false}"',
      "export npm_config_update_notifier",
      `exec "$${MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY}" "$${MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY}/bin/${target.npmEntry}" "$@"`,
    );
  } else {
    lines.push(`exec "$${MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY}" "$@"`);
  }
  return `${lines.join("\n")}\n`;
}

function renderPosixEnvGuard(envKey: string): string[] {
  return [
    `if [ -z "\${${envKey}:-}" ]; then`,
    `  echo "nibi node fallback: ${envKey} is not set" >&2`,
    `  exit ${MISSING_ENV_EXIT_CODE}`,
    "fi",
  ];
}

function renderWindowsShim(target: ShimTarget): string {
  const lines = [
    "@echo off",
    `rem Generated by NIBI: ${target.command} fallback on the Electron Node runtime.`,
    ...renderWindowsEnvGuard(MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY),
    ...(target.npmEntry ? renderWindowsEnvGuard(MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY) : []),
    "setlocal",
    'set "ELECTRON_RUN_AS_NODE=1"',
  ];
  if (target.npmEntry) {
    lines.push(
      'if not defined npm_config_update_notifier set "npm_config_update_notifier=false"',
      `"%${MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY}%" "%${MCP_NODE_FALLBACK_NPM_ROOT_ENV_KEY}%\\bin\\${target.npmEntry}" %*`,
    );
  } else {
    lines.push(`"%${MCP_NODE_FALLBACK_EXEC_PATH_ENV_KEY}%" %*`);
  }
  return `${lines.join("\r\n")}\r\n`;
}

function renderWindowsEnvGuard(envKey: string): string[] {
  return [
    `if not defined ${envKey} (`,
    `  echo nibi node fallback: ${envKey} is not set 1>&2`,
    `  exit /b ${MISSING_ENV_EXIT_CODE}`,
    ")",
  ];
}

/** 内容一致（POSIX 还要求可执行位齐全）时不触碰文件；否则写唯一临时文件再 rename。 */
export async function ensureMcpNodeFallbackShimDir(
  binDir: string,
  platform: NodeJS.Platform,
): Promise<void> {
  await mkdir(binDir, { recursive: true });
  await Promise.all(
    renderMcpNodeFallbackShims(platform).map((shim) => ensureShimFile(binDir, shim)),
  );
}

async function ensureShimFile(
  binDir: string,
  shim: { content: string; executable: boolean; name: string },
): Promise<void> {
  const shimPath = join(binDir, shim.name);
  if (await isShimCurrent(shimPath, shim)) return;

  const temporaryPath = `${shimPath}.tmp-${process.pid}-${randomUUID()}`;
  try {
    await writeFile(temporaryPath, shim.content, {
      mode: shim.executable ? SHIM_EXECUTABLE_MODE : undefined,
    });
    if (shim.executable) await chmod(temporaryPath, SHIM_EXECUTABLE_MODE);
    await rename(temporaryPath, shimPath);
  } catch (error) {
    await rm(temporaryPath, { force: true });
    throw error;
  }
}

async function isShimCurrent(
  shimPath: string,
  shim: { content: string; executable: boolean },
): Promise<boolean> {
  try {
    const [content, fileStat] = await Promise.all([readFile(shimPath, "utf8"), stat(shimPath)]);
    if (content !== shim.content) return false;
    return !shim.executable || (fileStat.mode & EXECUTABLE_BITS) === EXECUTABLE_BITS;
  } catch {
    return false;
  }
}

export async function resolveBundledNpmRoot(
  candidates: readonly string[],
): Promise<string | undefined> {
  for (const candidate of candidates) {
    if (
      (await isReadableFile(join(candidate, "bin", NPM_CLI_ENTRY))) &&
      (await isReadableFile(join(candidate, "bin", NPX_CLI_ENTRY)))
    ) {
      return candidate;
    }
  }
  return undefined;
}

async function isReadableFile(path: string): Promise<boolean> {
  try {
    await access(path, 0);
    return true;
  } catch {
    return false;
  }
}

/**
 * 与 MCP 适配器同一口径：插入顺序最后的键是后合并进来的值；Windows 全部大小写变体都算 PATH。
 */
function selectPathValue(
  env: Record<string, string | undefined>,
  platform: NodeJS.Platform,
): string {
  const keys = Object.keys(env).filter((key) =>
    platform === "win32" ? key.toUpperCase() === PATH_ENV_KEY : key === PATH_ENV_KEY,
  );
  return (keys.length > 0 ? env[keys[keys.length - 1]!] : undefined) ?? "";
}

/**
 * shim 目录追加为 PATH 最后一项；Windows 返回大写的 `PATH`，并把继承来的 `Path` 显式置
 * undefined（Node spawn 会跳过 undefined，子进程环境里就只剩一个区分大小写不敏感的 PATH）。
 */
export function fallbackPathPatch(
  currentPath: string,
  binDir: string,
  platform: NodeJS.Platform = process.platform,
): Record<string, string | undefined> {
  const pathApi = platform === "win32" ? win32 : posix;
  const delimiter = platform === "win32" ? win32.delimiter : posix.delimiter;
  const entries = currentPath.split(delimiter).filter(Boolean);
  const normalize = (value: string) => {
    const normalized = pathApi.normalize(value).replace(/[\\/]+$/, "");
    return platform === "win32" ? normalized.toLowerCase() : normalized;
  };
  if (entries.some((entry) => normalize(entry) === normalize(binDir))) {
    return platform === "win32" ? { PATH_ENV_KEY: currentPath, Path: undefined } : {};
  }
  const nextPath = currentPath ? `${currentPath}${delimiter}${binDir}` : binDir;
  return platform === "win32"
    ? { [PATH_ENV_KEY]: nextPath, Path: undefined }
    : { [PATH_ENV_KEY]: nextPath };
}

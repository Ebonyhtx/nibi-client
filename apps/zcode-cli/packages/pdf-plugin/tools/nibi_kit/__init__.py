"""NIBI 文档类插件的共享工具包（源真相）。

## 这个目录是什么

`plugins/_doc-kit/nibi_kit/` 是**规范源**：四个文档插件（documents / pdf / presentations /
spreadsheets）各自的 `tools/nibi_kit/` 都是它的**逐字副本**。插件包必须自包含（市场 zip 是
独立单元，不能跨包 import），所以副本是硬要求；一致性由仓库脚本 `tools/sync-doc-kit.py`
保证 —— 它既负责同步，也负责**断言四份副本与源完全一致**（改了一处忘了同步就报错）。

## 为什么不放进每个插件各写一份（各写一份的代价）

数模插件踩过这个坑：同一段「环境目录在哪」的逻辑抄在 5 个文件里，抄出的顺序有个共同缺陷
（拿不到环境变量就回退到**正式版安装**的数据目录）—— 一次隔离的 dev 运行静默读写了用户真实
安装的 venv 与 TeX 树，报错还指向别处。一份源 + 机械同步 + 一致性断言，是同一类缺陷的解药。

## 模块

| 模块 | 职责 |
| --- | --- |
| `env` | 插件自管 Python 环境（venv）的解析、自举安装、换解释器重跑 |
| `engines` | 真渲染引擎探测（LibreOffice）+ 转 PDF + PDF 逐页 PNG + 公式重算 |
| `fonts` | 字体文件定位（供自渲染与文字宽度估算用） |
| `textmetrics` | Excel 单元格文字的渲染宽度估算（截断/溢出判据的地基） |
| `hygiene` | 交付卫生：本机路径/用户名/指纹扫描与核心属性脱敏 |
| `gates` | 判据报告框架：每条判据必须报「比了多少项」，没跑到的判据必须显式出现 |
| `contact` | 缩略图观测表（一次把所有页面看全） |
| `cli` | CLI 公共骨架：UTF-8 输出、参数、退出码 |
"""
